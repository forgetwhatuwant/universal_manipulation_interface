#!/usr/bin/env python3
"""
Compare recorded Piper trajectory with target trajectory.
Loads the pickle file generated by replay_piper_camera_trajectory.py and visualizes the results.

Usage:
    python scripts_real/compare_piper_trajectory.py --input <replay_result.pkl>
"""

import os
import sys
import pickle
import click
import numpy as np
import matplotlib.pyplot as plt
from mpl_toolkits.mplot3d import Axes3D

ROOT_DIR = os.path.dirname(os.path.dirname(__file__))
sys.path.append(ROOT_DIR)

@click.command()
@click.option('--input', '-i', required=True, type=str, help='Path to replay result pickle file')
@click.option('--show', is_flag=True, default=True, help='Show plots')
@click.option('--save_plot', type=str, default=None, help='Save plot to file')
def main(input, show, save_plot):
    print(f"Loading results from: {input}")
    
    with open(input, 'rb') as f:
        data = pickle.load(f)
        
    target_poses = data['target_poses']
    target_timestamps = data['target_timestamps']
    actual_poses = data['actual_poses']
    actual_timestamps = data['actual_timestamps']
    actual_q = data.get('actual_q')
    actual_qd = data.get('actual_qd')
    config = data.get('config', {})
    
    if actual_poses is None or len(actual_poses) == 0:
        print("Error: No actual pose data found in file.")
        return

    # Normalize timestamps to start at 0
    t0 = target_timestamps[0]
    target_t = target_timestamps - t0
    actual_t = actual_timestamps - t0
    
    # Calculate duration stats
    duration = actual_t[-1]
    print(f"\nTrajectory Stats:")
    print(f"  Duration: {duration:.2f} s")
    print(f"  Samples: {len(actual_poses)}")
    print(f"  Average Rate: {len(actual_poses)/duration:.1f} Hz")
    
    if actual_q is not None:
        print(f"  Joint data available: Yes ({actual_q.shape[1]} joints)")
    
    # Create plots
    fig = plt.figure(figsize=(18, 12))
    plt.suptitle(f"Piper Trajectory Replay Analysis\n{os.path.basename(input)}", fontsize=16)
    
    # 1. 3D Path Comparison
    ax1 = fig.add_subplot(231, projection='3d')
    ax1.plot(target_poses[:, 0], target_poses[:, 1], target_poses[:, 2], 'b--', label='Target', alpha=0.7)
    ax1.plot(actual_poses[:, 0], actual_poses[:, 1], actual_poses[:, 2], 'r-', label='Actual', alpha=0.8)
    ax1.set_xlabel('X (m)')
    ax1.set_ylabel('Y (m)')
    ax1.set_zlabel('Z (m)')
    ax1.set_title('3D Path')
    ax1.legend()
    
    # 2. Position vs Time (XYZ)
    ax2 = fig.add_subplot(232)
    labels = ['X', 'Y', 'Z']
    colors = ['r', 'g', 'b']
    for i in range(3):
        ax2.plot(target_t, target_poses[:, i], color=colors[i], linestyle='--', alpha=0.5)
        ax2.plot(actual_t, actual_poses[:, i], color=colors[i], linestyle='-', label=f'{labels[i]}')
    ax2.set_title('Position over Time')
    ax2.set_xlabel('Time (s)')
    ax2.set_ylabel('Position (m)')
    ax2.legend()
    ax2.grid(True, alpha=0.3)
    
    # 3. Rotation vs Time (RxRyRz)
    ax3 = fig.add_subplot(233)
    labels = ['Rx', 'Ry', 'Rz']
    for i in range(3):
        ax3.plot(target_t, target_poses[:, 3+i], color=colors[i], linestyle='--', alpha=0.5)
        ax3.plot(actual_t, actual_poses[:, 3+i], color=colors[i], linestyle='-', label=f'{labels[i]}')
    ax3.set_title('Rotation over Time (Rotation Vector)')
    ax3.set_xlabel('Time (s)')
    ax3.set_ylabel('Rotation (rad)')
    ax3.legend()
    ax3.grid(True, alpha=0.3)
    
    # 4. Position Error
    ax4 = fig.add_subplot(234)
    # Resample target to match actual timestamps for error calculation
    from scipy.interpolate import interp1d
    
    # Ensure time ranges overlap
    t_min = max(target_t[0], actual_t[0])
    t_max = min(target_t[-1], actual_t[-1])
    mask = (actual_t >= t_min) & (actual_t <= t_max)
    eval_t = actual_t[mask]
    
    if len(eval_t) > 0:
        # Interpolate target to actual timestamps
        target_pos_interp = interp1d(target_t, target_poses[:, :3], axis=0, kind='linear', fill_value='extrapolate')(eval_t)
        actual_pos_eval = actual_poses[mask, :3]
        
        errors = np.linalg.norm(target_pos_interp - actual_pos_eval, axis=1) * 1000 # convert to mm
        rmse = np.sqrt(np.mean(errors**2))
        max_err = np.max(errors)
        
        ax4.plot(eval_t, errors, 'k-', alpha=0.7)
        ax4.set_title(f'Position Tracking Error (RMSE: {rmse:.1f} mm, Max: {max_err:.1f} mm)')
        ax4.set_xlabel('Time (s)')
        ax4.set_ylabel('Error (mm)')
        ax4.grid(True, alpha=0.3)
        ax4.axhline(rmse, color='r', linestyle='--', label=f'RMSE: {rmse:.1f} mm')
        ax4.legend()
    else:
        ax4.text(0.5, 0.5, "Time ranges do not overlap enough for error calc", ha='center')

    # 5. Joint Positions (if available)
    if actual_q is not None:
        ax5 = fig.add_subplot(235)
        for i in range(actual_q.shape[1]):
            ax5.plot(actual_t, actual_q[:, i], label=f'J{i+1}')
        ax5.set_title('Joint Positions')
        ax5.set_xlabel('Time (s)')
        ax5.set_ylabel('Angle (rad)')
        ax5.legend(fontsize='small', ncol=2)
        ax5.grid(True, alpha=0.3)
        
    # 6. Joint Velocities (if available)
    if actual_qd is not None:
        ax6 = fig.add_subplot(236)
        for i in range(actual_qd.shape[1]):
            ax6.plot(actual_t, actual_qd[:, i], label=f'J{i+1}')
        ax6.set_title('Joint Velocities')
        ax6.set_xlabel('Time (s)')
        ax6.set_ylabel('Velocity (rad/s)')
        ax6.legend(fontsize='small', ncol=2)
        ax6.grid(True, alpha=0.3)

    plt.tight_layout(rect=[0, 0.03, 1, 0.95])
    
    if save_plot:
        plt.savefig(save_plot)
        print(f"Plot saved to: {save_plot}")
        
    if show:
        plt.show()

if __name__ == '__main__':
    main()

